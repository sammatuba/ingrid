QUANTILE_RULE = (
    "each challenger's p10 and p90 are the 10 % and 90 % quantiles of its own as-of "
    "residual fan — the signed residuals (realized - point) of earlier settled windows, "
    "every one of them from a forecast made by a model fitted before its own origin and "
    "released only once such a window ended at least one embargo before the origin being "
    "forecast — added to its point forecast; the reported triple is those two arms and "
    "the point forecast sorted ascending, exactly as PRICE-2 reports its baselines' "
    "triples; bias, MAE and RMSE score the unadjusted point forecast"
)


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--regional", required=True, help="the regional hourly export")
    parser.add_argument("--nodal", help="the de-identified load-node export (optional)")
    parser.add_argument("--digests", help="the export digest record to check against")
    parser.add_argument("--scorecard", required=True, help="the PRICE-2 scorecard record")
    parser.add_argument("--out", help="write the comparison record here")
    parser.add_argument("--series", choices=("regional", "nodal", "both"), default="regional")
    parser.add_argument("--horizons", default=",".join(HORIZONS))
    parser.add_argument("--folds", type=int, default=6)
    parser.add_argument("--embargo-hours", type=int, default=24)
    parser.add_argument("--min-fan-samples", type=int, default=12)
    parser.add_argument("--min-train-rows", type=int, default=500)
    parser.add_argument("--fuel-history",
                        help="add the fuel features (src/price/fuel.py) from this history CSV")
    parser.add_argument("--data-label",
                        default=("pre-backfill exports (digests in docs/work/price-outlook/export.md); "
                                 "the run is regenerated by the data refresh, step D"),
                        help="the record's data_label: which exports this run read")
    parser.add_argument("--summary-series", default="regional",
                        help="which series the printed table covers (regional, nodal, both, none)")
    return parser.parse_args(argv)


def collect(args: argparse.Namespace) -> tuple[list[Series], list[dict]]:
    """Load the requested series and check the exported bytes by digest."""
    wanted: list[str] = []
    inputs: list[dict] = []
    digests = load_digests(args.digests) if args.digests else None
    if args.series in ("regional", "both"):
        wanted.append(args.regional)
    if args.series in ("nodal", "both") and args.nodal and Path(args.nodal).exists():
        wanted.append(args.nodal)
    if digests is not None:
        inputs = verify_inputs(wanted, digests)
    else:
        inputs = [{"file": Path(path).name, "sha256": digest_file(path)} for path in wanted]
    series: list[Series] = []
    if args.series in ("regional", "both"):
        series.extend(load_regional(args.regional))
    if args.series in ("nodal", "both") and args.nodal and Path(args.nodal).exists():
        series.extend(load_nodal(args.nodal))
    return series, inputs


def scored_table(record: dict, key: str, horizon: str) -> dict[str, list[dict]]:
    """The record's scored origins of one series and horizon, split by slice.

    Each entry carries the origin, the realized window value and every baseline's
    point forecast, which is the comparison basis the record was written for.
    """
    entry = next((item for item in record["series"] if item["key"] == key), None)
    if entry is None:
        raise SeriesError("SCORECARD_SERIES_MISSING", key)
    horizon_entry = next((item for item in entry["horizons"] if item["horizon"] == horizon),
                         None)
    if horizon_entry is None:
        raise SeriesError("SCORECARD_HORIZON_MISSING", f"{key}/{horizon}")
    columns = list(horizon_entry["origin_rows"]["columns"])
    table: dict[str, list[dict]] = {MARKET: [], AP: []}
    for row in horizon_entry["origin_rows"]["rows"]:
        values = dict(zip(columns, row))
        table.setdefault(values["slice"], []).append({
            "origin": values["origin"],
            "realized": float(values["realized"]),
            "baselines": {name: float(values[name]) for name in columns[4:]},
        })
    return table


def baseline_metrics_in_record(record: dict, key: str, horizon: str) -> dict[str, dict]:
    """The baselines' stored metrics of one series and horizon, by name and slice."""
    entry = next(item for item in record["series"] if item["key"] == key)
    horizon_entry = next(item for item in entry["horizons"] if item["horizon"] == horizon)
    stored = {}
    for baseline in horizon_entry["baselines"]:
        stored[baseline["name"]] = {name: dict(metrics)
                                    for name, metrics in baseline["slices"].items()}
    return stored


def series_section(series: Series, record: dict, args: argparse.Namespace,
                   horizons: tuple[str, ...]) -> dict:
    """One series' folds, walks and group assessments."""
    index = HistoryIndex(series)
    marks = derive_marks(series)
    extra = getattr(args, "fuel", None)
    pool = build_training_pool(index, series, marks, args.embargo_hours, extra=extra)
    scored_day = scored_table(record, series.key, "day")
    day_origins = sorted(date.fromisoformat(entry["origin"])
                         for name in (MARKET, AP) for entry in scored_day[name])
    folds = fold_definitions(day_origins, folds=args.folds)
    fitted = fit_folds(index, series, folds, default_challenger_factories(), pool=pool,
                       embargo_hours=args.embargo_hours, min_train_rows=args.min_train_rows)
    names = tuple(fitted[0].names)
    section = {
        "key": series.key,
        "kind": series.kind,
        "label": series.label,
        "rows": len(series.rows),
        "training_rows": len(pool),
        "training_origins": len({row[0] for row in pool}),
        "folds": [entry.to_dict() for entry in fitted],
        "horizons": [],
    }
    for horizon in horizons:
        result = walk(index, series, horizon, fitted, folds,
                      embargo_hours=args.embargo_hours, min_fan_samples=args.min_fan_samples,
                      extra=extra)
        by_origin = {entry.origin: entry for entry in result.candidates}
        unserved: dict[str, int] = {}
        for entry in result.candidates:
            if not entry.served:
                unserved[entry.reason] = unserved.get(entry.reason, 0) + 1
        table = scored_table(record, series.key, horizon)
        slices = {}
        for slice_name in (MARKET, AP):
            scored = table.get(slice_name, [])
            rows_for: dict[str, list[GroupRow]] = {name: [] for name in names}
            not_served = []
            realized_mismatch = 0
            for entry in scored:
                origin = date.fromisoformat(entry["origin"])
                candidate = by_origin.get(origin)
                if candidate is None or not candidate.served:
                    not_served.append(entry["origin"])
                    continue
                if abs(candidate.realized - entry["realized"]) > 1e-3:
                    realized_mismatch += 1
                for name in names:
                    rows_for[name].append(GroupRow(
                        origin=origin, fold=candidate.fold, realized=entry["realized"],
                        baseline=entry["baselines"], point=candidate.points[name],
                        quantiles=candidate.quantiles.get(name)))
            slices[slice_name] = {
                "scored_in_record": len(scored),
                "served": len(scored) - len(not_served),
                "origins_not_served": not_served,
                "realized_mismatches": realized_mismatch,
                "baselines_in_record": baseline_metrics_in_record(record, series.key, horizon),
                "challengers": {
                    name: assess_claim(rows_for[name], slice_name=slice_name,
                                       scored_in_record=len(scored), name=name)
                    for name in names
                },
            }
        section["horizons"].append({
            "horizon": horizon,
            "candidates": len(result.candidates),
            "served": sum(1 for entry in result.candidates if entry.served),
            "unserved": unserved,
            "slices": slices,
        })
    return section


def build_record(series_list: list[Series], inputs: list[dict], record: dict,
                 args: argparse.Namespace, horizons: tuple[str, ...]) -> dict:
    models = [model.to_dict() for model in default_challengers()]
    return {
        "kind": KIND,
        "version": VERSION,
        "data_label": args.data_label,
        "config": {
            "embargo_hours": args.embargo_hours,
            "folds": args.folds,
            "min_fan_samples": args.min_fan_samples,
            "min_train_rows": args.min_train_rows,
            "horizons": list(horizons),
            "features": list(FEATURES) + (list(FUEL_FEATURES) if getattr(args, "fuel", None) else []),
            "feature_floors": {
                "mean_last_24h_min_hours": MEAN24_MIN_HOURS,
                "mean_last_168h_min_hours": MEAN168_MIN_HOURS,
                "same_hour_7d_min_hours": SAME_HOUR_7D_MIN,
                "same_hour_28d_min_hours": SAME_HOUR_28D_MIN,
            },
            "models": models,
            "gate": {
                "basis": ("the best of the three PRICE-2 baselines by MAE on the common "
                          "origins, from the record's own per-origin point forecasts"),
                "min_common_share": MIN_COMMON_SHARE,
                "bootstrap": {"unit": "ISO week of the origin",
                              "resamples": BOOTSTRAP_RESAMPLES, "seed": BOOTSTRAP_SEED,
                              "level": BOOTSTRAP_LEVEL,
                              "rule": "the interval of the MAE gain must exclude zero"},
                "calibration": {
                    "coverage_floor": COVERAGE_FLOOR, "coverage_ceiling": COVERAGE_CEILING,
                    "fold_coverage_floor": FOLD_COVERAGE_FLOOR,
                    "fold_min_origins": FOLD_COVERAGE_MIN_ORIGINS,
                    "fold_share": FOLD_GAIN_SHARE,
                    "rule": ("the reported p10-p90 interval must cover between the floor and "
                             "the ceiling of the served origins overall, and at least the "
                             "fold floor in two thirds of the group's folds; a fold with "
                             "fewer than the fold minimum of judged origins measures nothing "
                             "and counts as a fold that fails"),
                },
                "fold_gain_share": FOLD_GAIN_SHARE,
                "market_only": "the administered-pricing slice never carries a skill claim",
            },
            "quantile_rule": QUANTILE_RULE,
            "target": ("the interval-weighted mean price of the window that begins at the "
                       "origin (PRICE-0 contract, PRICE-2 windows and clock)"),
        },
        "inputs": {
            "scorecard": {
                "file": Path(args.scorecard).name,
                "sha256": digest_file(args.scorecard),
                "version": record.get("version"),
                "kind": record.get("kind"),
            },
            "exports": inputs,
        },
        "series": [series_section(series, record, args, horizons) for series in series_list],
    }


def record_json(record: dict) -> str:
    return json.dumps(record, sort_keys=True, separators=(",", ":"), ensure_ascii=False,
                      allow_nan=False)


def print_summary(record: dict, which: str) -> None:
    print(f"{record['version']}: {len(record['series'])} series, "
          f"{record['config']['folds']} folds, embargo "
          f"{record['config']['embargo_hours']} h, "
          f"data label: {record['data_label']}")
    for entry in record["series"]:
        if which != "both" and entry["kind"] != which:
            continue
        print(f"\n{entry['key']} [{entry['kind']}] {entry['label']} "
              f"({entry['training_rows']} training rows over {entry['training_origins']} days)")
        for horizon in entry["horizons"]:
            print(f"  {horizon['horizon']:5} candidates {horizon['candidates']} "
                  f"served {horizon['served']} | unserved: "
                  f"{horizon['unserved'] or 'none'}")
            for slice_name in (MARKET, AP):
                group = horizon["slices"].get(slice_name)
                if not group or not group["scored_in_record"]:
                    continue
                print(f"    {slice_name:6} record n={group['scored_in_record']} "
                      f"served n={group['served']}")
                for baseline in sorted(group["baselines_in_record"]):
                    metrics = group["baselines_in_record"][baseline].get(slice_name) or {}
                    if not metrics.get("count"):
                        continue
                    print(f"      base  {baseline:31} n={metrics['count']:5} "
                          f"bias={metrics['bias']:10.3f} mae={metrics['mae']:10.3f} "
                          f"rmse={metrics['rmse']:10.3f}")
                for name, report in sorted(group["challengers"].items()):
                    metrics = report["metrics"]
                    gain = report.get("gain_mae")
                    shown = "n/a" if gain is None else format(gain, "10.3f")
                    print(f"      model {name:31} n={metrics['count']:5} "
                          f"bias={metrics['bias']:10.3f} mae={metrics['mae']:10.3f} "
                          f"rmse={metrics['rmse']:10.3f} gain_mae={shown}"
                          f" | {report['verdict']}")


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    horizons = tuple(name for name in args.horizons.split(",") if name)
    try:
        series, inputs = collect(args)
        args.fuel = None
        if args.fuel_history:
            args.fuel = FuelFeatures.from_csv(args.fuel_history)
            inputs.append({"file": Path(args.fuel_history).name,
                           "sha256": digest_file(args.fuel_history), "kind": "fuel-history"})
        record = json.loads(Path(args.scorecard).read_text(encoding="utf-8"))
        comparison = build_record(series, inputs, record, args, horizons)
    except (SeriesError, FuelError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    if args.summary_series != "none":
        print_summary(comparison, args.summary_series)
    text = record_json(comparison)
    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        # Exactly the canonical JSON whose SHA-256 is printed below, with no
        # trailing newline: the digest is the digest of the file's bytes.
        out.write_text(text, encoding="utf-8")
        print(f"\nwrote {out} ({out.stat().st_size} bytes)")
    print(f"content_digest {hashlib.sha256(text.encode('utf-8')).hexdigest()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
