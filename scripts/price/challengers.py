#!/usr/bin/env python3
"""Score the PRICE-3 challengers against the PRICE-2 baselines (stdlib only).

Reads the PRICE-1 exports and the PRICE-2 scorecard record under ``.local/price/``,
checks the exports against ``digests.json``, walks the challenged series
fold by fold (see ``src/price/challengers.py``) and writes the comparison record:
for every series, horizon and slice, the challengers' bias, MAE, RMSE and pinball
next to the baselines' — both scored on the same origins — and the gate's verdict
on whether a challenger may claim skill there.

    /usr/bin/python3 scripts/price/challengers.py \
        --regional .local/price/lwap_final_hourly.csv \
        --nodal .local/price/portfolio_nodal_hourly_deid.csv \
        --digests .local/price/digests.json \
        --scorecard .local/price/scorecard.json \
        --series both \
        --out .local/price/challengers.json

The record is deterministic: the same bytes, configuration and record give the
same JSON, and the printed ``content_digest`` is the SHA-256 of those bytes. The
file is written as the canonical JSON itself, with no trailing newline. No price
value, node name or portfolio volume is written into the repository.
"""
